const Joi = require('joi');

exports.createProjectSchema = Joi.object({
  name: Joi.string().required(),
  client_name: Joi.string().required(),
  client_id: Joi.string().uuid().allow('', null).optional(),
  project_type: Joi.string().valid('solar_pv', 'wind', 'td_lines', 'tower', 'pipeline', 'volumetric', 'other').required(),
  state: Joi.string().required(),
  district: Joi.string().optional(),
  location_name: Joi.string().allow('', null).optional(),
  status: Joi.string().valid('initiate','planned','on_going','executed','complete','cancelled').default('initiate'),
  start_date: Joi.date().iso().optional(),
  end_date: Joi.date().iso().min(Joi.ref('start_date')).optional().messages({
    'date.min': 'end_date must be on or after start_date',
  }),
  po_number: Joi.string().allow('', null).optional(),
  work_order_number: Joi.string().allow('', null).optional(),
  contact_person: Joi.string().allow('', null).optional(),
  contact_number: Joi.string().allow('', null).optional(),
  contact_email: Joi.string().email({ tlds: false }).allow('', null).optional(),
  latitude: Joi.number().min(-90).max(90).allow(null).optional(),
  longitude: Joi.number().min(-180).max(180).allow(null).optional(),
  description: Joi.string().allow('', null).optional(),
  needs_attention: Joi.boolean().optional(),
  // Allocation + scope fields handled by the service / separate endpoints
  pilot_id: Joi.string().allow('', null).optional(),
  drone_id: Joi.string().allow('', null).optional(),
  secondary_pilot_id: Joi.string().allow('', null).optional(),
  secondary_drone_id: Joi.string().allow('', null).optional(),
  scope: Joi.any().optional(),
  drone_flying_zone: Joi.string().valid('Green Zone', 'Yellow Zone', 'Red Zone').allow('', null).optional(),
});

exports.updateProjectSchema = Joi.object({
  name: Joi.string(),
  client_name: Joi.string(),
  client_id: Joi.string().uuid().allow('', null),
  project_type: Joi.string().valid('solar_pv', 'wind', 'td_lines', 'tower', 'pipeline', 'volumetric', 'other'),
  state: Joi.string(),
  district: Joi.string(),
  location_name: Joi.string().allow('', null),
  status: Joi.string().valid('initiate','planned','on_going','executed','complete','cancelled'),
  start_date: Joi.date().iso(),
  end_date: Joi.date().iso().min(Joi.ref('start_date')).messages({
    'date.min': 'end_date must be on or after start_date',
  }),
  po_number: Joi.string().allow('', null),
  work_order_number: Joi.string().allow('', null),
  contact_person: Joi.string().allow('', null),
  contact_number: Joi.string().allow('', null),
  contact_email: Joi.string().email({ tlds: false }).allow('', null),
  latitude: Joi.number().min(-90).max(90).allow(null),
  longitude: Joi.number().min(-180).max(180).allow(null),
  description: Joi.string().allow('', null),
  needs_attention: Joi.boolean(),
  pilot_id: Joi.string().allow('', null),
  drone_id: Joi.string().allow('', null),
  secondary_pilot_id: Joi.string().allow('', null),
  secondary_drone_id: Joi.string().allow('', null),
  scope: Joi.any(),
  drone_flying_zone: Joi.string().valid('Green Zone', 'Yellow Zone', 'Red Zone').allow('', null).optional(),
});
